"""Run one `codex exec` call and reject tool or unknown item events.

The optimization loop needs a text-in, text-out model call. This module runs
`codex exec --json`, streams the events to disk, parses the reply, and rejects
events outside the accepted text item types. The caller gets the reply text,
the thread ID for the next call, and the token usage.

CODEX_HOME supplies the configuration generated by make_codex_env.py. Use
probe_codex.py to check the declared tools in a locally captured request after
changing the CLI or configuration. Event checks apply to the CLI output, not
to activity the CLI does not report.
"""
import json
import os
import subprocess
import threading
import time
from pathlib import Path

# CLI item types treated as tool activity.
TOOL_ITEM_TYPES = {
    "command_execution",
    "file_change",
    "patch_apply",
    "mcp_tool_call",
    "web_search",
    "todo_list",
    "view_image",
    "image_generation",
}
# CLI item types accepted without a tool-activity error.
TEXT_ITEM_TYPES = {"agent_message", "reasoning", "error"}


class CodexError(RuntimeError):
    """The Codex call used a tool or produced an unknown event; the run must stop."""
    pass


def build_cmd(
    prompt: str,
    *,
    effort: str | None = None,
    model: str | None = None,
    resume: str | None = None,
    cwd: Path | None = None,
    last_message_file: Path | None = None,
    extra_args: list | None = None,
    codex_bin: str = "codex",
) -> list[str]:
    """Return the argv for one non-interactive call."""
    cmd = [codex_bin, "exec"]
    if resume:
        cmd += ["resume", resume]
    cmd += ["--json", "--skip-git-repo-check"]
    # Resume uses the session's stored directory; Popen also sets the process
    # directory. Only new sessions receive the -C option.
    if cwd is not None and not resume:
        cmd += ["-C", str(cwd)]
    if model:
        cmd += ["-m", model]
    if effort:
        cmd += ["-c", f'model_reasoning_effort="{effort}"']
    if last_message_file is not None:
        cmd += ["-o", str(last_message_file)]
    cmd += list(extra_args or [])
    cmd += [prompt]
    return cmd


def _stream(
    proc,
    sink: list,
    jsonl_path: Path,
    heartbeat: int,
    timeout: int,
    log,
    err_sink: list | None = None,
) -> bool:
    """Copy stdout to disk as it arrives. Return True if the call timed out."""
    handle = open(jsonl_path, "w")
    lock = threading.Lock()

    errs = err_sink if err_sink is not None else []

    def drain(stream, to_file, into):
        """Copy a stream line by line into a file and a list."""
        for line in iter(stream.readline, ""):
            with lock:
                into.append(line)
            if to_file:
                handle.write(line)
                handle.flush()

    threads = [
        threading.Thread(target=drain, args=(proc.stdout, True, sink), daemon=True),
        threading.Thread(target=drain, args=(proc.stderr, False, errs), daemon=True),
    ]
    for t in threads:
        t.start()
    start = time.time()
    next_beat = start + heartbeat
    timed_out = False
    while True:
        try:
            proc.wait(timeout=2)
            break
        except subprocess.TimeoutExpired:
            now = time.time()
            if now >= next_beat:
                log(f"[codex] ...running {int(now - start)}s, {len(sink)} event(s)")
                next_beat = now + heartbeat
            if now - start > timeout:
                log(f"[codex] HARD TIMEOUT after {int(now - start)}s")
                proc.kill()
                timed_out = True
                break
    for t in threads:
        t.join(timeout=5)
    handle.close()
    return timed_out


def parse_events(lines) -> dict:
    """Turn the JSONL event stream into one result record."""
    out = {
        "thread_id": None,
        "text": "",
        "usage": {},
        "items": [],
        "tool_items": [],
        "errors": [],
        "turn_failed": None,
    }
    texts = []
    for line in lines:
        line = line.strip()
        if not line:
            continue
        try:
            ev = json.loads(line)
        except json.JSONDecodeError:
            continue
        kind = ev.get("type")
        if kind == "thread.started":
            out["thread_id"] = ev.get("thread_id")
        elif kind in ("item.completed", "item.started"):
            item = ev.get("item") or {}
            itype = item.get("type")
            if itype in TOOL_ITEM_TYPES or itype not in TEXT_ITEM_TYPES:
                if itype not in out["tool_items"]:
                    out["tool_items"].append(itype)
            if kind == "item.completed":
                out["items"].append(itype)
                if itype == "agent_message":
                    texts.append(item.get("text") or "")
        elif kind == "turn.completed":
            out["usage"] = ev.get("usage") or {}
        elif kind == "turn.failed":
            out["turn_failed"] = (ev.get("error") or {}).get("message")
        elif kind == "error":
            out["errors"].append(ev.get("message"))
    out["text"] = "\n".join(t for t in texts if t)
    return out


def _feed_stdin(proc, text: str) -> None:
    """Write the prompt to CLI stdin and tolerate an already closed pipe."""
    try:
        proc.stdin.write(text)
        proc.stdin.close()
    except (BrokenPipeError, OSError, ValueError):
        pass


def call_codex(
    prompt: str,
    run_dir: Path,
    tag: str,
    codex_home: Path,
    *,
    effort: str | None = None,
    model: str | None = None,
    resume: str | None = None,
    cwd: Path | None = None,
    timeout: int = 5400,
    heartbeat: int = 30,
    extra_args: list | None = None,
    codex_bin: str = "codex",
    env: dict | None = None,
    log=print,
    stdin_text: str | None = None,
) -> dict:
    """Run one call. Raise CodexError for tool or unknown item events.

    The record holds text, thread_id, usage, items, and the raw event path.
    With stdin_text, the prompt argument is `-` and the prompt goes through
    stdin, avoiding the operating system's argument-length limit.
    """
    run_dir = Path(run_dir)
    run_dir.mkdir(parents=True, exist_ok=True)
    jsonl_path = run_dir / f"codex_{tag}.jsonl"
    last_msg = run_dir / f"codex_{tag}_last.txt"

    cmd = build_cmd(
        "-" if stdin_text is not None else prompt,
        effort=effort,
        model=model,
        resume=resume,
        cwd=cwd or run_dir,
        last_message_file=last_msg,
        extra_args=extra_args,
        codex_bin=codex_bin,
    )
    call_env = dict(os.environ if env is None else env)
    call_env["CODEX_HOME"] = str(codex_home)

    log(
        f"[codex] calling (tag={tag}, effort={effort or 'config'}"
        f"{', resume' if resume else ''})..."
    )
    proc = subprocess.Popen(
        cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        stdin=(subprocess.DEVNULL if stdin_text is None else subprocess.PIPE),
        bufsize=1,
        cwd=str(cwd or run_dir),
        env=call_env,
    )
    if stdin_text is not None:
        threading.Thread(
            target=_feed_stdin, args=(proc, stdin_text), daemon=True
        ).start()
    lines: list[str] = []
    errlines: list[str] = []
    timed_out = _stream(proc, lines, jsonl_path, heartbeat, timeout, log, errlines)

    rec = parse_events(lines)
    rec["timed_out"] = timed_out
    rec["returncode"] = None if timed_out else proc.returncode
    rec["events_path"] = str(jsonl_path)
    rec["cmd"] = cmd
    rec["stderr"] = "".join(errlines).strip()
    if not lines and rec["stderr"]:
        # Preserve an stderr excerpt when no stdout events were received.
        rec["errors"].append(rec["stderr"][:400])
    if last_msg.is_file() and not rec["text"]:
        rec["text"] = last_msg.read_text()

    usage = rec["usage"]
    rec["tokens"] = {
        "in_tok": int(usage.get("input_tokens") or 0),
        "cached_in_tok": int(usage.get("cached_input_tokens") or 0),
        "out_tok": int(usage.get("output_tokens") or 0),
        "reasoning_tok": int(usage.get("reasoning_output_tokens") or 0),
    }
    t = rec["tokens"]
    log(
        f"[codex] tokens in:{t['in_tok']} (cached:{t['cached_in_tok']}) "
        f"out:{t['out_tok']} (reasoning:{t['reasoning_tok']})"
    )

    if rec["tool_items"]:
        raise CodexError(
            f"TOOL USE DETECTED: {rec['tool_items']}. The reply is "
            f"not tool-free. See {jsonl_path}"
        )
    return rec
