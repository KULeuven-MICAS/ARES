"""Generate Codex configuration intended for text-only model calls.

Writes configuration, a model catalog, and a system prompt without copying
authentication, sessions, or caches. Regenerate them after changing the CLI
version, and check a locally captured request with probe_codex.py before running
the flow.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shutil

CATALOG_MARKER = b'{\n  "models": ['
OFF_FEATURES = [
    "unified_exec",
    "shell_tool",
    "view_image",
    "goals",
    "apps",
    "multi_agent",
    "tool_suggest",
    "skill_search",
    "sleep_tool",
    "hooks",
    "memories",
    "browser_use",
    "browser_use_external",
    "computer_use",
    "image_generation",
    "in_app_browser",
    "code_mode",
]
DEFAULT_SYSTEM_PROMPT = (
    "You are an expert RTL design engineer. You optimize Verilog and "
    "SystemVerilog modules for power, timing, and area. You have no tools. "
    "You answer with text only."
)


def find_codex_binary(cli: str) -> Path:
    """Find the standalone binary or the executable in an npm installation."""
    entry = shutil.which(cli)
    if entry is None:
        raise ValueError(
            f"CLI is unavailable: {cli}; install it or provide --codex-bin"
        )
    real = Path(entry).resolve()
    for parent in real.parents:
        if parent.name == "node_modules":
            candidates = sorted(parent.glob("@openai/codex-*/vendor/*/bin/codex"))
            candidates += sorted(parent.glob("@openai/codex/vendor/*/codex/codex"))
            if len(candidates) == 1:
                return candidates[0]
            if len(candidates) > 1:
                raise ValueError(
                    "multiple platform binaries found; provide --codex-bin explicitly"
                )
    if real.stat().st_size > 50_000_000:
        return real
    raise ValueError(
        f"cannot locate the executable next to {real}; provide --codex-bin"
    )


def extract_catalog(binary: Path) -> dict:
    """Decode the embedded JSON catalog without counting braces in strings."""
    raw = binary.read_bytes()
    start = raw.find(CATALOG_MARKER)
    if start < 0:
        raise ValueError(f"no recognized embedded model catalog in {binary}")
    # Binary data follows the JSON, so a byte-level scan finds the exact JSON
    # boundary while honoring quotes and escaped quotes in model instructions.
    depth = 0
    quoted = escaped = False
    for index in range(start, len(raw)):
        character = raw[index]
        if quoted:
            if escaped:
                escaped = False
            elif character == 92:
                escaped = True
            elif character == 34:
                quoted = False
        elif character == 34:
            quoted = True
        elif character in (123, 91):
            depth += 1
        elif character in (125, 93):
            depth -= 1
            if depth == 0:
                catalog = json.loads(raw[start : index + 1])
                if not isinstance(catalog.get("models"), list):
                    raise ValueError("embedded catalog has no model list")
                return catalog
    raise ValueError("embedded catalog is truncated")


def strip_tools(catalog: dict) -> dict:
    """Turn off the tool and skill instructions of every model in the catalog."""
    for model in catalog.get("models", []):
        model["apply_patch_tool_type"] = None
        model["include_skills_usage_instructions"] = False
        model["include_apps_usage_instructions"] = False
        model["include_plugin_usage_instructions"] = False
    return catalog


def write_config(
    home: Path, model: str, effort: str, catalog_path: Path, prompt_path: Path
) -> None:
    """Write config.toml with every tool, skill, and feature disabled."""
    quote = json.dumps
    features = "\n".join(f"{name} = false" for name in OFF_FEATURES)
    (home / "config.toml").write_text(
        f"""# Generated by make_codex_env.py. Verify with probe_codex.py after CLI changes.
model = {quote(model)}
model_reasoning_effort = {quote(effort)}
approval_policy = "never"
sandbox_mode = "read-only"
model_catalog_json = {quote(str(catalog_path))}
model_instructions_file = {quote(str(prompt_path))}
include_environment_context = false
include_apps_instructions = false
include_collaboration_mode_instructions = false
include_permissions_instructions = false
project_doc_max_bytes = 0
web_search = "disabled"

[tools]
web_search = false
experimental_request_user_input = {{ enabled = false }}
update_plan = {{ enabled = false }}

[skills]
bundled = {{ enabled = false, include_instructions = false }}

[features]
{features}
"""
    )


def main() -> int:
    """Create a clean Codex template home for text-only calls."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out", required=True, help="external template directory to create"
    )
    parser.add_argument(
        "--model", required=True, help="model ID from the installed CLI catalog"
    )
    parser.add_argument(
        "--effort",
        default="medium",
        choices=["low", "medium", "high"],
    )
    parser.add_argument("--cli", default=os.environ.get("CODEX_BIN", "codex"))
    parser.add_argument("--codex-bin", help="binary containing the embedded catalog")
    parser.add_argument(
        "--system-prompt", help="optional replacement system prompt file"
    )
    args = parser.parse_args()
    home = Path(args.out).expanduser().resolve()
    project = Path(__file__).resolve().parents[1]
    if home.is_relative_to(project):
        raise ValueError("--out must be outside the source directory")
    home.mkdir(parents=True, exist_ok=True)
    binary = (
        Path(args.codex_bin).expanduser().resolve()
        if args.codex_bin
        else find_codex_binary(args.cli)
    )
    catalog = strip_tools(extract_catalog(binary))
    slugs = [model["slug"] for model in catalog["models"]]
    if args.model not in slugs:
        raise ValueError(
            f"model {args.model!r} is absent from the installed catalog: {', '.join(slugs)}"
        )
    catalog_path = home / "catalog_clean.json"
    prompt_path = home / "system_prompt.txt"
    catalog_path.write_text(json.dumps(catalog))
    prompt_path.write_text(
        Path(args.system_prompt).read_text()
        if args.system_prompt
        else DEFAULT_SYSTEM_PROMPT
    )
    write_config(home, args.model, args.effort, catalog_path, prompt_path)
    print(f"[config] created {home}; model={args.model}; effort={args.effort}")
    print(
        "[config] authentication stays separate in CODEX_AUTH_HOME; no credentials were copied"
    )
    print(
        "[config] verify tools with probe_codex.py before using this CLI configuration"
    )
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError) as error:
        raise SystemExit(f"[FAIL] {error}") from None
